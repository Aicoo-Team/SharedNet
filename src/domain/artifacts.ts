function verificationMarkdown(mission: Mission): string {
  return `# Verification — ${mission.title}

Independent verifier: \`@sharednet/quality\`

${mission.verificationChecks
  .map(
    (check) =>
      `- [${check.status === "passed" ? "x" : " "}] ${check.label}\n  - Evidence: ${check.evidence}`,
  )
  .join("\n")}
`;
}

export function createHandoffArtifacts(mission: Mission): Artifact[] {
  const { brief } = mission;
  const artifacts: Artifact[] = [
    {
      id: "product-brief",
      name: "PRODUCT_BRIEF.md",
      kind: "brief",
      language: "markdown",
      content: briefMarkdown(brief),
      producedBy: "@sharednet/product",
      redacted: false,
    },
    {
      id: "architecture",
      name: "ARCHITECTURE.md",
      kind: "architecture",
      language: "markdown",
      content: architectureMarkdown(brief),
      producedBy: "@sharednet/architect",
      redacted: false,
    },
    ...(brief.requiresDatabase
      ? [
          {
            id: "schema",
            name: "schema.sql",
            kind: "schema" as const,
            language: "sql",
            content: schemaSql(brief),
            producedBy: "@sharednet/neon" as const,
            redacted: false,
          },
        ]
      : []),
    {
      id: "source",
      name: "app/page.tsx",
      kind: "source",
      language: "tsx",
      content: sourceArtifact(brief),
      producedBy: "@sharednet/builder",
      redacted: false,
    },
    {
      id: "readme",
      name: "README.md",
      kind: "readme",
      language: "markdown",
      content: readmeMarkdown(brief),
      producedBy: "@sharednet/builder",
      redacted: false,
    },
    {
      id: "infrastructure",
      name: "infrastructure.json",
      kind: "manifest",
      language: "json",
      content: JSON.stringify(
        {
          notice: "Secrets redacted. SIMULATED resources do not exist at providers.",
          connectors: mission.connectors,
        },
        null,
        2,
      ),
      producedBy: "@sharednet/vercel",
      redacted: true,
    },
    {
      id: "verification",
      name: "VERIFICATION.md",
      kind: "verification",
      language: "markdown",
      content: verificationMarkdown(mission),
      producedBy: "@sharednet/quality",
      redacted: false,
    },
  ];

  return artifacts;
}

export function isHandoffComplete(mission: Mission): boolean {
  const requiredNames = [
    "PRODUCT_BRIEF.md",
    "ARCHITECTURE.md",
    ...(mission.brief.requiresDatabase ? ["schema.sql"] : []),
    "app/page.tsx",
    "README.md",
    "infrastructure.json",
    "VERIFICATION.md",
  ];
  const artifactNames = new Set(mission.artifacts.map((artifact) => artifact.name));

  return (
    mission.status === "completed" &&
    mission.verificationChecks.every((check) => check.status === "passed") &&
    requiredNames.every((name) => artifactNames.has(name))
  );
}
