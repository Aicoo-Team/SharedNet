import type { Artifact, Mission, ProductBrief } from "./types";

function list(items: string[]): string {
  return items.map((item) => `- ${item}`).join("\n");
}

function briefMarkdown(brief: ProductBrief): string {
  return `# ${brief.title}

## Outcome

${brief.summary}

## Primary user

${brief.primaryUser}

## Core loop

${list(brief.coreLoop)}

## Access

${brief.accessModel}

## Visual direction

${brief.visualDirection}

## Acceptance criteria

${list(brief.acceptanceCriteria)}

## Assumptions

${list(brief.assumptions)}

## Deferred

${list(brief.deferredDecisions)}
`;
}

function architectureMarkdown(brief: ProductBrief): string {
  const dataLayer = brief.requiresDatabase
    ? "Neon Postgres behind server-owned data access"
    : "No persistent data layer in V1";

  return `# Architecture — ${brief.title}

## Runtime boundary

- Next.js application with a responsive server-rendered shell
- ${dataLayer}
- Vercel preview deployment behind an explicit connector approval gate
- Browser receives no provider credentials

## Product boundary

The build optimizes this loop:

${list(brief.coreLoop)}

## Access model

${brief.accessModel}

## Failure policy

- Provider creation errors fail closed.
- Ambiguous external writes enter reconciliation-required state.
- Deployment never becomes runnable before the local build artifact exists.
- Independent verification owns acceptance evidence.
`;
}

function safeSqlName(value: string): string {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .toLowerCase();
}

function schemaSql(brief: ProductBrief): string {
  return brief.dataModel
    .map((entity) => {
      const table = `${safeSqlName(entity.name)}s`;
      const specificColumns = entity.fields
        .filter((field) => !["id", "created_at", "updated_at"].includes(field))
        .map((field) => `  ${safeSqlName(field)} text not null`)
        .join(",\n");
      const columns = [
        "  id uuid primary key default gen_random_uuid()",
        specificColumns,
        "  created_at timestamptz not null default now()",
      ].filter(Boolean);

      return `-- ${entity.purpose}\ncreate table if not exists ${table} (\n${columns.join(",\n")}\n);`;
    })
    .join("\n\n");
}

function sourceArtifact(brief: ProductBrief): string {
  return `"use client";

import { useState } from "react";

const seed = [
  { id: 1, title: "A clearer first-run experience", votes: 18, status: "Planned" },
  { id: 2, title: "Weekly progress digest", votes: 12, status: "Reviewing" },
];

export default function ProductPage() {
  const [items, setItems] = useState(seed);
  const [title, setTitle] = useState("");

  function submit(event: React.FormEvent) {
    event.preventDefault();
    if (!title.trim()) return;
    setItems([{ id: Date.now(), title: title.trim(), votes: 1, status: "New" }, ...items]);
    setTitle("");
  }

  return (
    <main>
      <p>PUBLIC FEEDBACK BOARD</p>
      <h1>${brief.title}</h1>
      <p>${brief.outcome}</p>
      <form onSubmit={submit}>
        <label htmlFor="idea">Share an idea</label>
        <input id="idea" value={title} onChange={(event) => setTitle(event.target.value)} />
        <button type="submit">Submit idea</button>
      </form>
      {items.map((item) => (
        <article key={item.id}>
          <strong>{item.title}</strong>
          <span>{item.status}</span>
          <button onClick={() => setItems(items.map((candidate) =>
            candidate.id === item.id ? { ...candidate, votes: candidate.votes + 1 } : candidate
          ))}>▲ {item.votes}</button>
        </article>
      ))}
    </main>
  );
}
`;
}

